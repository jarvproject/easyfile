#!/bin/bash

# Проверяем, запущен ли скрипт с правами root (sudo)
if [ "$EUID" -ne 0 ]; then
  echo "Пожалуйста, запустите скрипт с sudo: sudo ./setup.sh"
  exit 1
fi

# 1. Проверяем наличие скомпилированного бинарника в текущей папке
if [ ! -f "easyfile" ]; then
  echo "Ошибка: Исполняемый файл 'easyfile' не найден в текущей директории."
  echo "Сначала скомпилируйте его: gcc main.c -o easyfile"
  exit 1
fi

echo "Установка easyfile..."

# 2. Копируем основной бинарник в /usr/bin/
cp easyfile /usr/bin/easyfile
chmod +x /usr/bin/easyfile

# 3. Создаем команду "setup", которая будет перезапускать этот же файл
# Делаем символическую ссылку (симлинк). Теперь 'setup' и 'easyfile' — это одна команда.
ln -sf /usr/bin/easyfile /usr/bin/setup

echo "--------------------------------------------------"
echo "Установка успешно завершена!"
echo "Теперь вам доступны команды навсегда:"
echo "  easyfile  — для запуска вашей программы"
echo "  setup     — для повторного вызова (аналог easyfile)"
echo "--------------------------------------------------"
